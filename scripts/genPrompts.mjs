// Writes apps/xr/src/edge/prompts.generated.ts from agents/prompts, so the Cloudflare function (no file system) uses
// the same canonical voice-agent specs as services/voice-gateway. A unit test fails if the two drift.
// Run: node scripts/genPrompts.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const files = {
  teamRules: "_team_rules",
  fieldNoteInterpreter: "field_note_interpreter",
  dialogueGrounding: "dialogue_grounding_agent",
  briefingComposer: "spoken_briefing_composer",
};
const body = Object.entries(files)
  .map(([key, stem]) => `  ${key}: ${JSON.stringify(readFileSync(join(root, "agents/prompts", `${stem}.md`), "utf8"))},`)
  .join("\n");
const out = `// Generated by scripts/genPrompts.mjs from agents/prompts. Do not edit by hand.
import type { VoicePrompts } from "../../../../services/voice-gateway/src/adapters/voicePrompts.js";

export const VOICE_PROMPTS: VoicePrompts = {
${body}
};
`;
writeFileSync(join(root, "apps/xr/src/edge/prompts.generated.ts"), out);
